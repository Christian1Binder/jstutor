-- Run once in the STRATO MySQL/MariaDB database. Not an installer exposed on the web.
CREATE TABLE tutor_users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 name VARCHAR(30) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE tutor_states (
 user_id BIGINT UNSIGNED NOT NULL,
 track VARCHAR(20) NOT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 state_json MEDIUMTEXT NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY (user_id, track),
 FOREIGN KEY (user_id) REFERENCES tutor_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE tutor_login_attempts (
 email_hash CHAR(64) NOT NULL,
 attempted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX attempts (email_hash, attempted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
